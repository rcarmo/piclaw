/** Shared, data-only web palette catalogue. Core and both web skins consume identical IDs/colours. */
export type ThemeMode = "light" | "dark";
export interface ThemePalette {
  bgPrimary: string;
  bgSecondary: string;
  bgHover?: string;
  textPrimary: string;
  textSecondary: string;
  borderColor: string;
  accent: string;
  accentHover?: string;
  danger: string;
  success: string;
  warning?: string;
  /** Authored code roles are separate from UI text/contrast adjustments. */
  codeBackground?: string;
  codeForeground?: string;
  syntax?: Record<string, string>;
  /** Authored ANSI roles; palette generation still enforces readable foregrounds. */
  terminal?: Record<string, string>;
  /** Preserve a single phosphor hue in contrast fallbacks and interaction overlays. */
  monochrome?: boolean;
}
export interface ThemePreset {
  id: string;
  label: string;
  mode: ThemeMode | "auto";
  light?: ThemePalette;
  dark?: ThemePalette;
  glow?: boolean;
  source?: string;
}
